// The world map above was drawn with a light ocean, which washes out against
// the wallpaper it hangs on. Flip it once at load so the land reads light on a
// dark sea and the two pins stay the darkest thing on it.
DECALS.worldmap = DECALS.worldmap.map(function (row) {
  return row.replace(/[012]/g, function (c) {
    return c === '0' ? '2' : (c === '1' ? '0' : '3');
  });
});

// ------------------------------------------------------------------- validation
// Catches a mistyped row immediately instead of letting it corrupt the screen.

function validateArt() {
  const problems = [];
  const checkGrid = (name, rows, w, h) => {
    if (rows.length !== h) problems.push(name + ': ' + rows.length + ' rows, expected ' + h);
    rows.forEach((row, i) => {
      if (row.length !== w) problems.push(name + ' row ' + i + ': ' + row.length + ' cols, expected ' + w);
      if (/[^.0123]/.test(row)) problems.push(name + ' row ' + i + ': bad character');
    });
  };
  for (const k in GROUND) checkGrid('GROUND.' + k, GROUND[k], TILE, TILE);
  for (const k in OBJECTS) checkGrid('OBJECTS.' + k, OBJECTS[k], TILE, TILE);
  for (const dir in PLAYER) {
    PLAYER[dir].forEach((f, i) => checkGrid('PLAYER.' + dir + '[' + i + ']', f, TILE, TILE));
  }
  for (const k in DECALS) checkGrid('DECALS.' + k, DECALS[k], 32, 32);
  return problems;
}
